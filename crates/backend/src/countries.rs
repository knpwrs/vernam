#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn countries_have_desktops_names_codes_and_order() {
        let all = countries();
        // Every name Desktop has has a calling code.
        assert_eq!(all.len(), NAMES.len());
        assert_eq!(calling_code("CP"), None, "Clipperton Island has none");
        assert_eq!(country("GB").map(|c| (c.name, c.code)), Some(("United Kingdom", "+44".into())));
        assert_eq!(country("US").map(|c| c.code), Some("+1".into()));
        // Desktop's overrides.
        assert_eq!(country("XK").map(|c| c.code), Some("+383".into()));
        assert_eq!(country("AQ").map(|c| c.code), Some("+672".into()));
        // By name, as Desktop's `<` sorts them: "Åland Islands" after "Zimbabwe".
        assert_eq!(all.first().map(|c| c.name), Some("Afghanistan"));
        assert!(all.windows(2).all(|w| w[0].name.encode_utf16().cmp(w[1].name.encode_utf16()).is_le()));
    }
}
