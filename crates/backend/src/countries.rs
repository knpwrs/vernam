//! Countries for "Find by phone number" (Desktop's `getCountryData.dom.ts`):
//! every region Desktop names in English, with its calling code.
//!
//! The names are Desktop's own (`build/country-display-names.json`, its
//! English map), in Desktop's order: by name, compared by UTF-16 code unit
//! as its `<` compares them.

use presage::libsignal_service::prelude::phonenumber;

/// A country to pick (Desktop's `CountryDataType`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Country {
    /// Its region code (`GB`).
    pub region: &'static str,
    /// Its English name.
    pub name: &'static str,
    /// Its calling code, with the plus (`+44`).
    pub code: String,
}

/// Every country with a calling code, in Desktop's order (one without,
/// as Clipperton Island would be, is left out, as Desktop's throw would).
pub fn countries() -> Vec<Country> {
    NAMES
        .iter()
        .filter_map(|&(region, name)| Some(Country { region, name, code: format!("+{}", calling_code(region)?) }))
        .collect()
}

/// The country `region` names, if it's one listed.
pub fn country(region: &str) -> Option<Country> {
    let &(region, name) = NAMES.iter().find(|(r, _)| *r == region)?;
    Some(Country { region, name, code: format!("+{}", calling_code(region)?) })
}

/// A region's calling code: libphonenumber's, or Desktop's for the regions
/// it has none for (`getCountryCodeForRegion`, after Signal-iOS).
pub fn calling_code(region: &str) -> Option<u16> {
    let code = match region {
        "AQ" | "HM" => 672,
        "BV" => 55,
        "IC" | "EA" => 34,
        "CP" => return None,
        "DG" => 246,
        "TF" => 262,
        "XK" => 383,
        "PN" => 64,
        "GS" => 500,
        "UM" => 1,
        _ => phonenumber::metadata::DATABASE.by_id(region)?.country_code(),
    };
    Some(code)
}

